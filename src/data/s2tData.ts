/**
 * 将任意文本转换为标准繁体字（正体字）
 */
export function toTraditional(text: string): string {
  if (!text) return '';
  return text
    .split('')
    .map((char) => S2T_MAP[char] || char)
    .join('');
}

/**
 * 将繁体字转换为简体字（用于部分兼容回退）
 */
export function toSimplified(text: string): string {
  if (!text) return '';
  return text
    .split('')
    .map((char) => T2S_MAP[char] || char)
    .join('');
}

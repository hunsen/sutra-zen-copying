/**
 * 获取汉字标准笔画数
 * @param char 单个汉字字符
 * @returns 标准笔画数（未收录字提供基于汉字复杂度的智能预估，默认 8）
 */
export function getExpectedStrokeCount(char: string): number {
  if (!char) return 1;
  const firstChar = char.charAt(0);
  if (SUTRA_STROKE_COUNT_MAP[firstChar] !== undefined) {
    return SUTRA_STROKE_COUNT_MAP[firstChar];
  }

  // 未收录汉字（如自建字帖中的罕见字）：根据 Unicode 区间与笔画均值提供保守预估
  return 8;
}

/**
 * 判断当前书写状态是否已基本完成该字
 * 考虑连笔/行书差异，允许误差 1 笔
 * @param currentStrokeCount 当前已书写笔画数
 * @param expectedCount 标准笔画数
 */
export function isCharacterComplete(
  currentStrokeCount: number,
  expectedCount: number
): boolean {
  if (currentStrokeCount <= 0) return false;
  if (expectedCount <= 3) return currentStrokeCount >= expectedCount;
  // 4 笔以上汉字，允许至多 1 笔连笔结合（如折笔合一），避免过早抢跑走纸
  return currentStrokeCount >= expectedCount - 1;
}
